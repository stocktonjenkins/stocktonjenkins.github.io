export interface Reference {
  /** Citation key, e.g. "vaswani2017attention". Unique within a post. */
  key: string
  title: string
  authors: string[]
  year?: string
  venue?: string
  url?: string
}

export interface Post {
  id: string
  title: string
  subtitle: string
  slug: string
  coverUrl: string
  tags: string[]
  /** BlockNote document, JSON-encoded (Firestore can't store nested arrays). */
  content: string
  references: Reference[]
  published: boolean
  publishedAt: number | null
  createdAt: number
  updatedAt: number
  readingMinutes: number
  /** Short blurb for the post list. Generated by Gemini or written by hand. */
  summary: string
  /** True while `summary` is unedited model output, so readers can be told. */
  summaryAi: boolean
  /** Reader visits, counted once per browser per day. Excludes the admin. */
  views: number
  /** Id of the series this post belongs to, or null. */
  series: string | null
  /** Optional manual position within the series; falls back to publish date. */
  seriesOrder: number | null
}

/**
 * An umbrella for posts about one ongoing project. Readable by the public only
 * while `listed` is true, which is kept equal to "has a published post"
 * (see refreshSeriesListed), so an unannounced project never leaks.
 */
export interface Series {
  id: string
  slug: string
  title: string
  description: string
  status: 'active' | 'complete'
  listed: boolean
  createdAt: number
  updatedAt: number
}

/** Admin-only settings stored at config/ai (never shipped in the site bundle). */
export interface AiConfig {
  geminiKey: string
  model: string
}

export type PostSummary = Omit<Post, 'content' | 'references'>
